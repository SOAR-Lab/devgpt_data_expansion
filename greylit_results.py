import pandas as pd
data = pd.read_csv('/content/GreyLitAssessment - final_sources_shriya.csv')
data.head()

#extracting debt types from RQ1
# Standardize and split debts
data["debt_types"] = data["RQ1"].dropna().apply(
    lambda x: [d.strip().lower() for d in x.split(",")]
)

data.head()

from collections import Counter
import matplotlib.pyplot as plt
import seaborn as sns

all_debts = [debt for sublist in data["debt_types"].dropna() for debt in sublist]
debt_counts = Counter(all_debts)

# Bar Chart
debt_df = pd.DataFrame(debt_counts.items(), columns=["Debt Type", "Frequency"])
debt_df = debt_df.sort_values("Frequency", ascending=False)

sns.barplot(x="Debt Type", y="Frequency", data=debt_df, palette="Blues_d")
plt.xticks(rotation=45)
plt.title("Frequency of Technical Debt Types")
plt.tight_layout()
plt.xlabel("Debt Type")
plt.ylabel("Frequency")
plt.xticks(rotation=90)
plt.show()

from sklearn.preprocessing import MultiLabelBinarizer

mlb = MultiLabelBinarizer()
debt_binary_matrix = mlb.fit_transform(data["debt_types"].dropna())

# Create a DataFrame for heatmap
co_occurrence = pd.DataFrame(debt_binary_matrix, columns=mlb.classes_)
correlation_matrix = co_occurrence.T.dot(co_occurrence)  # Simple co-occurrence count

sns.heatmap(correlation_matrix, annot=True, fmt="d", cmap="Blues")
plt.title("Technical Debt Co-occurrence Matrix")
plt.tight_layout()
plt.show()

